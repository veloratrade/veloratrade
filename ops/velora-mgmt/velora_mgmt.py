def _read(path: str) -> str:
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def _strip_sql_comments(sql: str) -> str:
    sql = re.sub(r"--[^\n]*", "", sql)
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.S)
    return sql


def _split_top_level(body: str) -> list[str]:
    """Split a CREATE TABLE body on commas at parenthesis depth 0."""
    parts: list[str] = []
    depth = 0
    buf = ""
    for ch in body:
        if ch == "(":
            depth += 1; buf += ch
        elif ch == ")":
            depth -= 1; buf += ch
        elif ch == "," and depth == 0:
            parts.append(buf); buf = ""
        else:
            buf += ch
    if buf.strip():
        parts.append(buf)
    return parts


def _extract_create_block(sql: str, start: int) -> tuple[str, str, int]:
    """Given index of the '(' opening a CREATE TABLE body, return (body, tail, end_index)
    by balancing parentheses. tail = text after the matching ')' up to the statement ';'."""
    assert sql[start] == "("
    depth = 0
    i = start
    while i < len(sql):
        if sql[i] == "(":
            depth += 1
        elif sql[i] == ")":
            depth -= 1
            if depth == 0:
                body = sql[start + 1:i]
                semi = sql.find(";", i)
                tail = sql[i + 1:semi if semi != -1 else len(sql)]
                return body, tail, (semi if semi != -1 else len(sql))
        i += 1
    return sql[start + 1:], "", len(sql)


def _parse_coldef(p: str, pos: int) -> Column | None:
    cm = re.match(r"`?(\w+)`?\s+(.*)$", p, re.S)
    if not cm:
        return None
    cname = cm.group(1)
    rest = re.sub(r"\s+", " ", cm.group(2).strip())
    tm = re.match(r"([a-zA-Z]+(?:\s*\([^)]*\))?(?:\s+(?:unsigned|zerofill))*)", rest, re.I)
    full_type = tm.group(1).strip() if tm else rest.split()[0]
    nullable = "NOT NULL" not in rest.upper()
    dm = re.search(r"DEFAULT\s+('(?:[^']*)'|[A-Za-z0-9_.()]+)", rest, re.I)
    default = dm.group(1) if dm else None
    return Column(name=cname, column_type=_norm_type(full_type),
                  data_type=re.split(r"[ (]", full_type)[0].lower(),
                  is_nullable=nullable, column_default=default, ordinal_position=pos)


def _parse_create_tables(sql: str) -> dict[str, dict]:
    """Purpose-specific parser for the project's CREATE TABLE blocks (proper paren
    balancing). Returns {table: {columns, indexes, fks, engine, charset, collation}}."""
    out: dict[str, dict] = {}
    for m in re.finditer(r"CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?\s+`?(\w+)`?\s*\(",
                         sql, flags=re.S | re.IGNORECASE):
        tname = m.group(1)
        open_paren = sql.find("(", m.start())
        body, tail, _ = _extract_create_block(sql, open_paren)
        cols: list[Column] = []
        indexes: list[Index] = []
        fks: list[ForeignKey] = []
        pos = 0
        for part in _split_top_level(body):
            p = re.sub(r"\s+", " ", part.strip())
            up = p.upper()
            if up.startswith("PRIMARY KEY"):
                inner = p[p.find("(") + 1:p.rfind(")")]
                keycols = [x.strip("` ") for x in inner.split(",")]
                indexes.append(Index(name="PRIMARY", columns=keycols, unique=True))
            elif up.startswith("UNIQUE KEY") or up.startswith("UNIQUE INDEX"):
                mm = re.match(r"UNIQUE\s+(?:KEY|INDEX)\s+`?(\w+)`?\s*\((.*)\)\s*$", p, re.I | re.S)
                if mm:
                    cc = [x.strip("` ") for x in mm.group(2).split(",")]
                    indexes.append(Index(name=mm.group(1), columns=cc, unique=True))
            elif up.startswith("KEY ") or up.startswith("INDEX "):
                mm = re.match(r"(?:KEY|INDEX)\s+`?(\w+)`?\s*\((.*)\)\s*$", p, re.I | re.S)
                if mm:
                    cc = [x.strip("` ") for x in mm.group(2).split(",")]
                    indexes.append(Index(name=mm.group(1), columns=cc, unique=False))
            elif up.startswith("CONSTRAINT") and "FOREIGN KEY" in up:
                mm = re.match(r"CONSTRAINT\s+`?(\w+)`?\s+FOREIGN\s+KEY\s*\(`?(\w+)`?\)\s*"
                              r"REFERENCES\s+`?(\w+)`?\s*\(`?(\w+)`?\)", p, re.I | re.S)
                if mm:
                    fks.append(ForeignKey(name=mm.group(1), column=mm.group(2),
                                          ref_table=mm.group(3), ref_column=mm.group(4)))
            elif re.match(r"^`?\w+`?\s+", p):
                pos += 1
                c = _parse_coldef(p, pos)
                if c:
                    cols.append(c)
        eng = charset = coll = None
        em = re.search(r"ENGINE\s*=\s*(\w+)", tail, re.I)
        if em: eng = em.group(1)
        cm2 = re.search(r"DEFAULT\s+CHARSET\s*=\s*(\w+)", tail, re.I)
        if cm2: charset = cm2.group(1)
        clm = re.search(r"COLLATE\s*=?\s*(\w+)", tail, re.I)
        if clm: coll = clm.group(1)
        out[tname] = {"columns": cols, "indexes": indexes, "fks": fks,
                      "engine": eng, "charset": charset, "collation": coll}
    return out


def _norm_type(t: str) -> str:
    t = re.sub(r"\s+", " ", t.strip())
    # lowercase the type keyword but preserve enum/set value case for comparison
    m = re.match(r"^([a-z]+)(.*)$", t, re.I)
    if m and m.group(1).lower() in ("enum", "set"):
        return m.group(1).lower() + re.sub(r"\s+", "", m.group(2))
    return re.sub(r"\s+", " ", t.lower())


def _norm_default(d: str | None) -> str | None:
    if d is None:
        return None
    d = d.strip()
    if len(d) >= 2 and d[0] == "'" and d[-1] == "'":
        d = d[1:-1]  # string default: compare unquoted value
    return d


def expected_schema(repo_root: str) -> Schema:
    """Build EXPECTED state at HEAD: baseline schema.sql plus additive migrations
    v1.0 and v1.1 (both ship in the repo and define the target schema)."""
    schema_sql = _read(os.path.join(repo_root, "api/database/schema.sql"))
    tables = _parse_create_tables(_strip_sql_comments(schema_sql))

    # --- v1.0: additive ALTERs (apply to expected baseline). The migration wraps
    # each statement in a SET @sql = IF(..., 'ALTER TABLE ... ADD COLUMN ...', 'SELECT 1');
    # so parse the ALTER text inside those string literals. ---
    v10 = _strip_sql_comments(_read(os.path.join(repo_root, MIGRATION_FILES["v1.0"])))
    for am in re.finditer(r"ALTER TABLE (\w+) ADD COLUMN (\w+) (.+?)(?: AFTER \w+)?',", v10, re.I):
        tname, cname, spec = am.group(1), am.group(2), am.group(3).strip()
        spec = spec.rstrip("'")
        ent = tables.setdefault(tname, {"columns": [], "indexes": [], "fks": [],
                                        "engine": "InnoDB", "charset": "utf8mb4",
                                        "collation": "utf8mb4_unicode_ci"})
        tm = re.match(r"([a-zA-Z]+(?:\s+unsigned)?(?:\s*\([^)]*\))?)", spec)
        full_type = tm.group(1).strip() if tm else spec.split()[0]
        nullable = "NOT NULL" not in spec.upper()
        dm = re.search(r"DEFAULT\s+('(?:[^']*)'|[A-Za-z0-9_.]+)", spec, re.I)
        default = dm.group(1) if dm else None
        ent["columns"].append(Column(
            name=cname, column_type=_norm_type(full_type),
            data_type=full_type.split("(")[0].split()[0],
            is_nullable=nullable, column_default=default,
            ordinal_position=len(ent["columns"]) + 1))
    # ADD KEY / ADD UNIQUE KEY
    for im in re.finditer(r"ALTER TABLE (\w+) ADD (?:UNIQUE )?KEY (\w+) \(([^)]*)\)',", v10, re.I):
        tname, iname, cols = im.group(1), im.group(2), im.group(3)
        unique = "UNIQUE" in im.group(0).upper().split("KEY")[0]
        cc = [x.strip("` ") for x in cols.split(",")]
        tables[tname]["indexes"].append(Index(name=iname, columns=cc, unique=unique))

    # --- v1.1: CREATE TABLE metaapi_fills ---
    v11 = _strip_sql_comments(_read(os.path.join(repo_root, MIGRATION_FILES["v1.1"])))
    for tname, ent in _parse_create_tables(v11).items():
        tables[tname] = ent

    s = Schema(database="<expected>", engine_version="MySQL 8.0 / MariaDB 11 (target)")
    for tname, ent in tables.items():
        s.tables[tname] = Table(
            name=tname, engine=ent.get("engine"), table_type="BASE TABLE",
            collation=ent.get("collation"), columns=ent["columns"],
            indexes=ent["indexes"], foreign_keys=ent["fks"], exists=True)
    return s


