def _tf(v: Any) -> bool:
    return str(v).upper() == "YES"


def schema_from_probe(meta: dict) -> Schema:
    """Normalize the read-only probe JSON (produced by the PHP probe) into a Schema.

    Expected probe shape (see ops/velora-mgmt/probe/inspect.php):
      scalars: {VERSION:{rows:[{v:..}]}, sql_mode:{rows:[{v:..}]}, ...}
      tables:  {rows:[{TABLE_NAME,ENGINE,TABLE_TYPE,TABLE_COLLATION,TABLE_ROWS}, ...]}
      focus:   {<table>: {exists:bool, columns:{rows:[...]}, statistics:{rows:[...]},
                          key_usage:{rows:[...]}}}
    Only information_schema / @@ metadata is consumed; no row data.
    """
    sc = meta.get("scalars", {})

    def scalar(key: str) -> str | None:
        node = sc.get(key) or {}
        if not node.get("ok"):
            return None
        rows = node.get("rows") or []
        if not rows:
            return None
        row = rows[0]
        if "v" in row:
            return row["v"]
        # SHOW VARIABLES style: {Variable_name, Value}
        return row.get("Value")

    s = Schema(
        database=scalar("current_database"),
        engine_version=scalar("VERSION"),
        charset_server=scalar("character_set_server"),
        collation_server=scalar("collation_server"),
        charset_database=scalar("character_set_database"),
        collation_database=scalar("collation_database"),
        sql_mode=scalar("sql_mode") or "",
        transaction_isolation=scalar("transaction_isolation"),
    )

    for row in (meta.get("tables", {}).get("rows") or []):
        tname = row["TABLE_NAME"]
        s.tables[tname] = Table(
            name=tname,
            engine=row.get("ENGINE"),
            table_type=row.get("TABLE_TYPE"),
            collation=row.get("TABLE_COLLATION"),
            table_rows=row.get("TABLE_ROWS"),
            exists=True,
        )

    for tname, entry in (meta.get("focus") or {}).items():
        if not entry.get("exists"):
            # table explicitly reported missing
            s.tables.setdefault(tname, Table(name=tname, exists=False))
            s.tables[tname].exists = False
            continue
        t = s.tables.setdefault(tname, Table(name=tname, exists=True))
        t.exists = True
        for c in (entry.get("columns", {}).get("rows") or []):
            t.columns.append(Column(
                name=c["COLUMN_NAME"],
                column_type=c["COLUMN_TYPE"],
                data_type=c.get("DATA_TYPE", ""),
                is_nullable=_tf(c.get("IS_NULLABLE")),
                column_default=c.get("COLUMN_DEFAULT"),
                ordinal_position=int(c.get("ORDINAL_POSITION", 0)),
            ))
        # group statistics by index
        idx: dict[str, dict] = {}
        for st in (entry.get("statistics", {}).get("rows") or []):
            name = st["INDEX_NAME"]
            g = idx.setdefault(name, {"cols": {}, "non_unique": int(st.get("NON_UNIQUE", 1))})
            g["cols"][int(st["SEQ_IN_INDEX"])] = st["COLUMN_NAME"]
        for name, g in idx.items():
            cols = [g["cols"][k] for k in sorted(g["cols"])]
            t.indexes.append(Index(name=name, columns=cols, unique=(g["non_unique"] == 0)))
        seen_fk: dict[str, ForeignKey] = {}
        for ku in (entry.get("key_usage", {}).get("rows") or []):
            cname = ku["CONSTRAINT_NAME"]
            ref_t = ku.get("REFERENCED_TABLE_NAME")
            fk = seen_fk.get(cname) or ForeignKey(
                name=cname, column=ku["COLUMN_NAME"],
                ref_table=ref_t or "", ref_column=ku.get("REFERENCED_COLUMN_NAME") or "")
            seen_fk[cname] = fk
        t.foreign_keys = list(seen_fk.values())
    return s


