def redact_db_name(name: str | None) -> str:
    """Database names may encode the account; mask the account-prefix but keep the
    environment suffix so audit output is useful without leaking the account id."""
    if not name:
        return "<unknown>"
    if "_" in name:
        head, _, tail = name.rpartition("_")
        return f"***_{tail}"
    return "***"


