def _colmap(t: Table) -> dict[str, Column]:
    return {c.name: c for c in t.columns}


def compare(actual: Schema, expected: Schema) -> dict:
    """Deterministic structural diff. Read-only; never mutates. Unexpected tables/
    columns are REPORTED, never auto-fixed."""
    diff: dict[str, Any] = {
        "missing_tables": [],
        "unexpected_tables": [],
        "tables": {},
        "engine_notes": [],
    }
    exp_names = set(expected.tables)
    act_names = {n for n, t in actual.tables.items() if t.exists}

    for t in sorted(exp_names - act_names):
        diff["missing_tables"].append(t)
    # tables present in actual but not expected (report for review; never auto-fix)
    for t in sorted(act_names - exp_names):
        diff["unexpected_tables"].append(t)

    for tname in sorted(exp_names):
        et = expected.tables[tname]
        at = actual.tables.get(tname)
        td: dict[str, Any] = {"exists": bool(at and at.exists), "missing_columns": [],
                              "type_mismatches": [], "nullability_mismatches": [],
                              "default_mismatches": [], "missing_indexes": [],
                              "missing_foreign_keys": [], "engine_mismatch": None,
                              "collation_mismatch": None, "column_detail_captured": False}
        # Missing entirely from actual, or explicitly reported exists=False.
        if at is None or not at.exists:
            if tname not in [t for t in diff["missing_tables"]]:
                pass
            diff["tables"][tname] = td
            if at is None:
                # not already listed via exp-act name sets only when exists=True
                if tname not in diff["missing_tables"]:
                    diff["missing_tables"].append(tname)
            continue
        # Exists but column-level metadata was not captured (probe only details focus
        # tables): report existence/engine, do NOT fabricate missing columns.
        if not at.columns and et.columns:
            td["column_detail_captured"] = False
            if et.engine and at.engine and at.engine.lower() != et.engine.lower():
                td["engine_mismatch"] = {"actual": at.engine, "expected": et.engine}
            diff["tables"][tname] = td
            continue
        td["column_detail_captured"] = True
        ac, ec = _colmap(at), _colmap(et)
        for cname in ec:
            if cname not in ac:
                td["missing_columns"].append(cname); continue
            a, e = ac[cname], ec[cname]
            if _norm_type(a.column_type) != _norm_type(e.column_type):
                td["type_mismatches"].append({"column": cname,
                    "actual": a.column_type, "expected": e.column_type})
            if a.is_nullable != e.is_nullable:
                td["nullability_mismatches"].append({"column": cname,
                    "actual": a.is_nullable, "expected": e.is_nullable})
            if (a.column_default or None) != (e.column_default or None):
                td["default_mismatches"].append({"column": cname,
                    "actual": a.column_default, "expected": e.column_default})
        aidx = {i.name: i for i in at.indexes}
        for i in et.indexes:
            if i.name not in aidx:
                td["missing_indexes"].append({"name": i.name, "columns": i.columns,
                                              "unique": i.unique})
        afk = {f.name: f for f in at.foreign_keys}
        for f in et.foreign_keys:
            if f.name not in afk:
                td["missing_foreign_keys"].append({"name": f.name, "column": f.column,
                                                   "ref": f"{f.ref_table}.{f.ref_column}"})
        if et.engine and at.engine and at.engine.lower() != et.engine.lower():
            td["engine_mismatch"] = {"actual": at.engine, "expected": et.engine}
        if et.collation and at.collation and at.collation.lower() != et.collation.lower():
            td["collation_mismatch"] = {"actual": at.collation, "expected": et.collation}
        diff["tables"][tname] = td
    return diff


