"""
VELORA Environment Management System — reusable, environment-aware, approval-gated
deployment & database-management engine.

Targets:   staging | production   (ALWAYS explicit; never inferred, never fall back)
Modes:     inspect | plan | backup | migrate | deploy | verify   (default = inspect/plan = READ-ONLY)

This module is PURE LOGIC. It performs NO network I/O, NO SQL execution, NO file
mutation outside the audit artifacts it is told to write. The actual DB transport is
the proven GitHub Actions -> FTP -> one-use PHP probe -> Database::connection() path
(see ops/velora-mgmt/probe/*.php and .github/workflows/velora-mgmt.yml); this engine
consumes the probe's read-only metadata JSON and produces deterministic plans/hashes
and approval decisions.

Hard rules enforced here:
  * target environment must be explicit and is validated against an allow-list.
  * no credential mixing / no cross-environment fallback.
  * an approval is bound to (environment, operation, commit_sha, migration_versions,
    plan_hash) and is invalid if ANY of those change.
  * production mutating operations require a verified backup in addition to approval.
  * no destructive SQL (DROP DATABASE/TABLE, TRUNCATE, DELETE) is ever generated by the
    migration planner; rollback is a separate, explicitly-approved mechanism.

The engine never prints secret values.
"""

