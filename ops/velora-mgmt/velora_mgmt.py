def pending_migrations(actual: Schema, expected: Schema) -> list[str]:
    """Deterministically decide which repo migrations are NOT yet applied, using
    structural signatures (not a migration table). v1.0 applied iff all its columns
    and indexes exist; v1.1 applied iff metaapi_fills exists."""
    pending = []
    prov = _migration_provides("v1.0")
    t = actual.tables.get("trades")
