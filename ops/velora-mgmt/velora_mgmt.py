@dataclass
class Approval:
    environment: str
    operation: str
    commit_sha: str
    migrations: list[str]
    plan_hash: str
    state: str = "APPROVED"

    @staticmethod
    def from_token(token: dict) -> "Approval":
        return Approval(
            environment=token["environment"], operation=token["operation"],
            commit_sha=token["commit_sha"], migrations=sorted(token.get("migrations", [])),
            plan_hash=token["plan_hash"], state=token.get("state", "APPROVED"))


def validate_approval(plan: dict, approval: Approval | None,
                      backup_verified: bool, target_environment: str) -> dict:
    """Return a decision. Production mutating ops additionally require a verified
    backup; approval is environment-scoped and bound to exact commit/migrations/hash."""
    reasons: list[str] = []
    env = plan["environment"]
    if target_environment != env:
        reasons.append(f"target mismatch: requested {target_environment} but plan is for {env}")
    if approval is None:
        reasons.append("no approval supplied")
    else:
        if approval.environment != env:
            reasons.append(f"approval is for {approval.environment}, cannot authorize {env}")
        if approval.operation != plan["operation"]:
            reasons.append("approval operation mismatch")
        if approval.commit_sha != plan["commit_sha"]:
            reasons.append("approval commit_sha mismatch")
        if sorted(approval.migrations) != sorted(plan["migrations"]):
            reasons.append("approval migration set mismatch")
        if approval.plan_hash != plan["plan_hash"]:
            reasons.append("approval plan_hash mismatch (plan changed; re-approval required)")
    cfg = ENV_CONFIG[env]
    if cfg["backup_required_before_change"] and not backup_verified:
        reasons.append("production change requires a VERIFIED pre-change backup (none verified)")
    if plan["forbidden_sql_hits"]:
        reasons.append("plan contains forbidden/destructive SQL")
    allowed = not reasons
    return {"allowed": allowed, "decision": "EXECUTE" if allowed else "STOP", "reasons": reasons}


