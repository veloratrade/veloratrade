@dataclass
class Column:
    name: str
    column_type: str          # e.g. varchar(64), bigint unsigned, datetime
    data_type: str            # e.g. varchar, bigint, datetime
    is_nullable: bool
    column_default: str | None
    ordinal_position: int

    def signature(self) -> str:
        d = "NULL" if self.is_nullable else "NOT NULL"
        default = "" if self.column_default is None else f" DEFAULT {self.column_default}"
        return f"{self.name} {self.column_type} {d}{default}"


@dataclass
class Index:
    name: str
    columns: list[str]
    unique: bool


@dataclass
class ForeignKey:
    name: str
    column: str
    ref_table: str
    ref_column: str


@dataclass
class Table:
    name: str
    engine: str | None = None
    table_type: str | None = None
    collation: str | None = None
    table_rows: int | None = None
    exists: bool = True
    columns: list[Column] = field(default_factory=list)
    indexes: list[Index] = field(default_factory=list)
    foreign_keys: list[ForeignKey] = field(default_factory=list)


@dataclass
class Schema:
    database: str | None = None
    engine_version: str | None = None
    charset_server: str | None = None
    collation_server: str | None = None
    charset_database: str | None = None
    collation_database: str | None = None
    sql_mode: str | None = None
    transaction_isolation: str | None = None
    tables: dict[str, Table] = field(default_factory=dict)

    def table_names(self) -> list[str]:
        return sorted(self.tables)


